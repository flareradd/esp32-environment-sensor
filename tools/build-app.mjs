#!/usr/bin/env node
// Builds the app for the device to serve, and embeds it in the firmware.
//
//   node tools/build-app.mjs           write firmware/statchain/app_assets.h
//   node tools/build-app.mjs --check   exit 1 if that header is out of date with app/
//
// Why a bundle: the ESP32's web server handles one connection at a time, and the browser opens
// several in parallel for a page of ~30 modules, so loading them one by one would be slow and
// erratic. Bundled, a page load is five or six small requests.
//
// The output is a handful of files (index.html, app.js, app.css, manifest, icons), gzipped where
// that helps, as a C header the firmware serves straight from flash.
// Nothing here is needed to *use* the app in development (tools/serve-app.mjs serves app/ directly).

import { build, transform } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';

const APP = fileURLToPath(new URL('../app/', import.meta.url));
export const HEADER_PATH = fileURLToPath(new URL('../firmware/statchain/app_assets.h', import.meta.url));

const MIME = {
  html: 'text/html; charset=utf-8', js: 'text/javascript; charset=utf-8', css: 'text/css; charset=utf-8',
  webmanifest: 'application/manifest+json', svg: 'image/svg+xml', png: 'image/png',
};
const mimeOf = (path) => MIME[path.split('.').pop()];

function replaceOnce(text, from, to, what) {
  if (!text.includes(from)) throw new Error(`build-app: could not find ${what} in index.html (${from})`);
  return text.replace(from, to);
}

// Returns [{ path, mime, raw: Buffer, gz: Buffer|null, etag }]. `gz` is set only when gzip is smaller.
export async function buildApp() {
  const bundle = await build({
    entryPoints: [`${APP}js/main.js`], bundle: true, format: 'esm', target: 'es2020', minify: true,
    write: false, legalComments: 'none', logLevel: 'silent',
  });
  const js = bundle.outputFiles[0].text;
  const css = (await transform(await readFile(`${APP}css/app.css`, 'utf8'), { loader: 'css', minify: true })).code;

  let html = await readFile(`${APP}index.html`, 'utf8');
  html = replaceOnce(html, 'href="css/app.css"', 'href="app.css"', 'the stylesheet link');
  html = replaceOnce(html, 'src="js/main.js"', 'src="app.js"', 'the script tag');
  // Tells the app it is being served by the device itself, so the device address is simply this origin.
  html = replaceOnce(html, '<meta charset="utf-8">', '<meta charset="utf-8">\n<meta name="statchain-host" content="device">', 'the charset meta');

  const files = [
    ['/index.html', Buffer.from(html)],
    ['/app.js', Buffer.from(js)],
    ['/app.css', Buffer.from(css)],
    ['/manifest.webmanifest', await readFile(`${APP}manifest.webmanifest`)],
    ...(await Promise.all(['icon.svg', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png', 'apple-touch-icon.png']
      .map(async (n) => [`/icons/${n}`, await readFile(`${APP}icons/${n}`)]))),
  ];
  return files.map(([path, raw]) => {
    const z = gzipSync(raw, { level: 9 });
    return {
      path, mime: mimeOf(path), raw, gz: z.length < raw.length ? z : null,
      etag: `"${createHash('sha1').update(raw).digest('hex').slice(0, 16)}"`,
    };
  });
}

// ---------------------------------------------------------------------------
// C header: what the firmware compiles in
// ---------------------------------------------------------------------------
export function renderHeader(assets) {
  const out = [
    '// GENERATED by tools/build-app.mjs from app/ - do not edit by hand.',
    '// Rebuild with: npm run build:app      (tests fail if this file is out of date)',
    '#pragma once',
    '#include <pgmspace.h>',
    '#include <stddef.h>',
    '#include <stdint.h>',
    '',
    'struct AppAsset {',
    '  const char* path;',
    '  const char* mime;',
    '  const uint8_t* data;  // gzip stream if `gzip`, else the file as is',
    '  size_t len;',
    '  bool gzip;',
    '  const char* etag;',
    '};',
    '',
  ];
  assets.forEach((a, i) => {
    const bytes = a.gz ?? a.raw;
    const lines = [];
    for (let o = 0; o < bytes.length; o += 32) lines.push('  ' + [...bytes.subarray(o, o + 32)].join(',') + ',');
    out.push(`// ${a.path}  (${a.raw.length} bytes${a.gz ? `, ${a.gz.length} gzipped` : ''})`);
    out.push(`static const uint8_t ASSET_${i}[] PROGMEM = {`, ...lines, '};', '');
  });
  out.push('static const AppAsset APP_ASSETS[] = {');
  assets.forEach((a, i) => {
    const n = (a.gz ?? a.raw).length;
    out.push(`  {"${a.path}", "${a.mime}", ASSET_${i}, ${n}, ${a.gz ? 'true' : 'false'}, "\\"${a.etag.slice(1, -1)}\\""},`);
  });
  out.push('};', 'static const size_t APP_ASSET_COUNT = sizeof(APP_ASSETS) / sizeof(APP_ASSETS[0]);', '');
  return out.join('\n');
}

// Reads a generated header back into assets (used by tests to prove it matches app/).
export function parseHeader(text) {
  const bodies = new Map();
  for (const m of text.matchAll(/static const uint8_t ASSET_(\d+)\[\] PROGMEM = \{([^}]*)\};/g)) {
    bodies.set(+m[1], Buffer.from(m[2].split(',').map((s) => s.trim()).filter(Boolean).map(Number)));
  }
  const out = [];
  for (const m of text.matchAll(/\{"([^"]+)", "([^"]+)", ASSET_(\d+), (\d+), (true|false), "\\"([0-9a-f]+)\\""\}/g)) {
    const data = bodies.get(+m[3]);
    if (!data || data.length !== +m[4]) throw new Error(`header: asset ${m[1]} length mismatch`);
    out.push({ path: m[1], mime: m[2], gzip: m[5] === 'true', data, etag: `"${m[6]}"` });
  }
  return out;
}

// ---------------------------------------------------------------------------
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const assets = await buildApp();
  const text = renderHeader(assets);
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(HEADER_PATH, 'utf8'); } catch { /* missing */ }
    // Compare the *content* (what the firmware would serve), not zlib's exact bytes.
    const same = (() => {
      try {
        const have = parseHeader(current);
        return have.length === assets.length && assets.every((a, i) => have[i].path === a.path && have[i].etag === a.etag);
      } catch { return false; }
    })();
    if (!same) { console.error('firmware/statchain/app_assets.h is out of date. Run: npm run build:app'); process.exit(1); }
    console.log('app_assets.h is up to date');
  } else {
    await writeFile(HEADER_PATH, text);
    const total = assets.reduce((n, a) => n + (a.gz ?? a.raw).length, 0);
    for (const a of assets) console.log(`${a.path.padEnd(32)} ${String(a.raw.length).padStart(7)} -> ${String((a.gz ?? a.raw).length).padStart(7)}${a.gz ? ' gz' : ''}`);
    console.log(`total ${total} bytes in flash; wrote ${HEADER_PATH}`);
  }
}
